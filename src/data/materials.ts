/** Materials offered for a given product recipe (falls back to uploads). */
export const materialsForRecipe = (recipe: RecipeScope = 'upload'): Material[] => {
  const list = materials.filter((m) => m.recipes.includes(recipe));
  return list.length ? list : materials.filter((m) => m.recipes.includes('upload'));
};
